"""Wrap the verified slide data as scripts for the live charts.

The browser deck must also work when index.html is opened from disk, where
fetch() of a JSON file is blocked. Each JSON stays the single source; this
script only repackages it, value for value.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'docs/slides/data'

for stem, name, check in [
    ('monthly-20260928', 'ES_MONTHLY', lambda d: len(d['monthly']) == 68),
    ('descriptive-20260928', 'ES_ANNUAL', lambda d: len(d['annual']) == 6),
    ('original-results', 'ES_ORIGINAL', lambda d: len(d['expectations_table_7a']) == 18),
    ('media-context-20260921', 'ES_MEDIA', lambda d: len(d['monthly']) == 68 and len(d['themes']) == 8),
]:
    data = json.loads((DATA / f'{stem}.json').read_text(encoding='utf-8'))
    assert check(data), stem
    payload = json.dumps(data, ensure_ascii=False, separators=(',', ':'))
    (DATA / f'{stem}.js').write_text(
        f'/* Generated by scripts/build-live-data.py from {stem}.json. Do not edit. */\n'
        f'window.{name}={payload};\n', encoding='utf-8')
    print(f'Wrote {stem}.js')
